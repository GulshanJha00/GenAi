import json
from dotenv import load_dotenv
load_dotenv()
from groq import Groq
import subprocess


client = Groq()

system_prompt = """
You are a Code and Testcase Generation AI Agent.

OBJECTIVE:
The user provides a programming problem in natural language.
Your job is to generate the required source code and testcases,
then create a project folder containing both files.

You must accomplish everything using the available tools.

AVAILABLE TOOLS:
- run_command:
  Accepts a shell command as a string, executes it,
  and returns the execution result.

STRICT RULES:
1. Return ONLY valid JSON.
2. Never use Markdown code blocks.
3. Never include text outside JSON.
4. Never claim an operation succeeded without receiving
   a successful tool execution result.
5. Never skip workflow steps.
6. Execute only one command per ACTION.
7. Every command must be generated by you.
8. Do not ask the user to manually create files.
9. After receiving a tool execution result, return exactly one ACTION object.
10. Never combine multiple JSON objects in one response.
11. Never return OBSERVE or OUTPUT in the same response as PLAN or ACTION.
12. Wait for the Python application to request the next step.

WORKFLOW:

STEP 1: PLAN

Analyse the user's request.

Determine:
- Programming language.
- Project folder name.
- Source code filename and extension.
- Testcase filename and extension.
- Required shell command.

Return:
{
    "step": "plan",
    "content": "Description of the next operation",
    "function": "run_command",
    "input": "shell command"
}

STEP 2: ACTION

The Python application will execute the command
provided in the PLAN step using run_command.

You will receive the execution result.

Return:
{
    "step": "action",
    "content": "Description of the execution result"
}

If the command fails, analyse the error and create
another PLAN step to fix it.

STEP 3: REPEAT

Continue alternating between PLAN and ACTION.

For example:
- Create project directory.
- Create source code file.
- Write source code into the file.
- Create testcase file.
- Write testcases into the file.
- Execute the source code against testcases.

Each operation must have its own PLAN and ACTION.

IMPORTANT:
To write code into a file, generate a valid shell command
that writes the actual code content into that file.

Do not use placeholder commands such as:
"add code to file"
"write testcases"

Generate executable shell commands instead.

STEP 4: OBSERVE

After all files are created and execution is completed,
analyse the results returned by Python.

Check whether:
- Source code executes successfully.
- Testcases execute successfully.
- Actual outputs match expected outputs.

Return:
{
    "step": "observe",
    "content": "Summary of validation results"
}

If validation fails, return to PLAN and ACTION
to correct the problem.

STEP 5: OUTPUT

Only proceed after successful validation.

Return:
{
    "step": "output",
    "content": "Project created successfully",
    "directory": "project directory",
    "files": [
        "source code file",
        "testcase file"
    ]
}

EXAMPLE:

User input:
"Create a program to add two numbers in Python"

Expected sequence:

1. PLAN: mkdir -p add
2. ACTION: Execute mkdir command.
3. PLAN: Generate add.py using a shell file-writing command.
4. ACTION: Execute command.
5. PLAN: Generate testcase.py using a shell file-writing command.
6. ACTION: Execute command.
7. PLAN: Execute testcase.py to validate add.py.
8. ACTION: Execute command.
9. OBSERVE: Analyse test results.
10. OUTPUT: Report successful file creation.

JSON RESPONSE REQUIREMENTS:

Every response must be a single JSON object.
The response must always contain a "step" field.
Allowed step values:
- plan
- action
- observe
- output
Never return an empty response.
Never return arrays or plain strings.


IMPORTANT:
- Each response must contain ONLY its current step.
- Never combine multiple steps into one response.
- Never skip a step.
- Never invent tool execution results.
- Always use valid JSON.
- The function name must match an available tool.
- The input field must contain an executable shell command.

"""




def run_command(command):
    result = subprocess.run(
        command,
        shell=True,
        capture_output=True,
        text=True
    )

    return {
        "stdout": result.stdout,
        "stderr": result.stderr,
        "returncode": result.returncode
    }


available_tools = {
    "run_command":{
        "fn": run_command,
        "description": "takes input of command, execute it and returns the result"
    }
}


message = [
{"role": "system","content": system_prompt}
]

query = input(">")
message.append({"role":"user","content":query})

while True:
    chat_completion = client.chat.completions.create(
        messages=message,
        temperature=0,
        reasoning_format="hidden",  
        response_format={"type": "json_object"},
        model="openai/gpt-oss-120b",
    )

    response = chat_completion.choices[0].message.content

    if not response:
        print("LLM returned empty response")

        print("Finish reason:",
            chat_completion.choices[0].finish_reason)
        break

    try:
        parsed_res = json.loads(response)

    except json.JSONDecodeError as e:
        print("Invalid JSON:", repr(response))
        print("Error:", e)
        break
    message.append({"role":"assistant","content":json.dumps(parsed_res)})

    if parsed_res.get("step") == "plan":
        funct_name = parsed_res.get("function")
        func_input = parsed_res.get("input")

        if funct_name in available_tools:
            output = available_tools[funct_name]["fn"](func_input)

            message.append({
                "role": "user",
                "content": f"Tool execution result: {json.dumps(output)}"
            })


    if parsed_res.get("step") != "output":
        message.append({
            "role": "user",
            "content": f"""
            You have completed the {parsed_res.get('step')} step.
            Now execute the next step in the workflow.
            """
        })
    
    print(f"🧠: {parsed_res.get('content')} ")

    if parsed_res.get('step') == "output":
        print(f"🤖: {parsed_res.get('content')}")
        break
